// Usage: node scripts/e2e/sheets.mjs <outdir> — screenshots of every sheet / drawer, light and dark
import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
const shot = async (n) => { await page.waitForTimeout(450); await page.screenshot({ path: `${out}/${n}.png` }); };
const close = () => page.click('.sheet button[aria-label="Close"]');
const key = (l) => page.click(`.bezel-bottom button[aria-label="${l}"]`);
await page.goto('http://127.0.0.1:5173/');
await page.waitForSelector('.chassis:not(.boot)');
await page.waitForTimeout(1200);
await key('Sprint'); await shot('s01-sprint'); await close();
await page.click('.slip-tab'); await page.keyboard.type('an overheard thing'); await shot('s02-catch'); await page.click('.slip-acts button:first-child');
await page.click('.legend button:nth-child(3)'); await page.waitForTimeout(600);
await page.click('.gut >> nth=0'); await shot('s03-line-menu'); await close();
await page.click('.ktag >> nth=0'); await shot('s04-section'); await close();
await page.click('.take >> nth=0'); await shot('s05-takes'); await close();
await page.click('button[aria-label="Cadence"] >> nth=0'); await shot('s06-cadence'); await close();
await page.click('.mblock.add'); await shot('s07-add'); await close();
await page.click('.deck .dchip:nth-child(4)'); await shot('s08-bpm'); await close();
await page.click('.deck .dchip:nth-child(3)'); await shot('s09-tuning'); await close();
await page.click('.mblock >> nth=0'); await shot('s10-mapbar'); await page.click('.mblock >> nth=0');
await key('Chords'); await shot('s11-chords'); await key('Chords');
await page.click('button[aria-label="Tapes"]'); await page.waitForTimeout(300);
await page.click('.jc-menu'); await shot('s12-tape-menu');
await page.click('.sheet .choice:has-text("EXPORT")'); await shot('s13-export');
await page.click('.sheet .btn:has-text("LYRIC CARD")'); await page.waitForTimeout(1500); await shot('s14-card'); await close();
await page.click('button[aria-label="Tapes"]').catch(() => {}); await page.waitForTimeout(200);
await page.click('.bezel-bottom button[aria-label="Import"]').catch(() => {}); await shot('s15-import'); await close();
await page.click('.bezel-bottom button[aria-label="Bin"]').catch(() => {}); await shot('s16-bin');
await page.click('button[aria-label="Tapes"]');
await page.click('button[aria-label="Setup"]');
await page.click('.sheet button:has-text("CHARCOAL")'); await page.click('.sheet button:has-text("MIDNIGHT")'); await close();
await page.click('.legend button:nth-child(3)'); await page.waitForTimeout(500);
await shot('s17-dark-bench');
await key('Words'); await page.waitForTimeout(400); await shot('s18-dark-words'); await key('Words');
await page.click('.gut >> nth=0'); await shot('s19-dark-line-menu'); await close();
await page.click('.legend button:nth-child(2)'); await page.waitForTimeout(500); await key('Deal'); await shot('s20-dark-table');
await page.click('.legend button:nth-child(1)'); await page.waitForTimeout(500); await shot('s21-dark-roll');
await key('Stand'); await page.waitForTimeout(300);
await page.click('.legend button:nth-child(3)').catch(() => {}); await page.waitForTimeout(400); await key('Stand'); await shot('s22-dark-stand');
console.log(errors.join('\n') || 'no errors');
await browser.close();
