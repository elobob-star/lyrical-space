// Usage: node scripts/e2e/tour.mjs <outdir> [width height] — screenshots of every surface (fresh profile)
import { chromium } from 'playwright';
const out = process.argv[2];
const W = Number(process.argv[3] ?? 390), H = Number(process.argv[4] ?? 844);
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
const shot = async (n) => { await page.waitForTimeout(500); await page.screenshot({ path: `${out}/${n}.png` }); };
await page.goto('http://127.0.0.1:5173/');
await page.waitForSelector('.chassis:not(.boot)');
await page.waitForTimeout(1500);
await shot('01-roll');
await page.click('button[aria-label="Draw"]');
await shot('02-roll-draw');
await page.click('button[aria-label="Pen"]');
const sp = page.locator('.roll-mirror span[data-s]').first();
const b = await sp.boundingBox();
await page.mouse.click(b.x + 60, b.y + 10);
await page.waitForTimeout(200);
await shot('03-roll-pen');
await page.click('button[aria-label="Pen"]');
await page.click('button[aria-label="Latch"]');
await page.locator('.roll-input').click();
await page.keyboard.press('Control+End');
await page.keyboard.type(' and on and on we go');
await shot('04-roll-latch');
await page.click('button[aria-label="Latch"]');
await page.click('.legend button:nth-child(2)');
await page.waitForTimeout(600);
await page.click('button[aria-label="Deal"]');
await page.waitForTimeout(900);
await shot('05-table');
const st = page.locator('.strip').nth(1);
const sb = await st.boundingBox();
await page.mouse.click(sb.x + 20, sb.y + 12);
await shot('06-table-selected');
await page.click('.legend button:nth-child(3)');
await page.waitForTimeout(700);
await shot('07-bench');
await page.click('button[aria-label="Lens"]');
await shot('08-bench-rhyme');
await page.click('button[aria-label="Lens"]');
await shot('09-bench-meter');
await page.click('button[aria-label="Lens"]');
await page.locator('.lin').first().click();
await page.keyboard.press('End');
await page.click('button[aria-label="Words"]');
await page.waitForTimeout(800);
await shot('10-bench-words');
await page.click('button[aria-label="Shoebox"]');
await shot('11-bench-shoebox');
await page.click('button[aria-label="Chords"]');
await shot('12-bench-chords');
await page.click('button[aria-label="Chords"]');
await page.click('button[aria-label="Stand"]');
await shot('13-stand');
await page.click('button[aria-label="Close the stand"]');
await page.click('button[aria-label="Tapes"]');
await shot('14-rack');
await page.click('button[aria-label="Shoebox"]');
await shot('15-rack-shoebox');
await page.click('button[aria-label="Tapes"]');
await page.click('button[aria-label="Setup"]');
await shot('16-setup');
await page.click('.sheet button:has-text("CHARCOAL")');
await page.click('.sheet button[aria-label="Close"]');
await page.click('.legend button:nth-child(1)');
await shot('17-charcoal-roll');
console.log(errors.join('\n') || 'no errors');
await browser.close();
